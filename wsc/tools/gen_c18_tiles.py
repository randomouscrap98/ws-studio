#!/usr/bin/env python3
"""Generate the C18 tile-map test background.

The background has 264 unique bank-0 tiles, a 4-tile cgb_tileset and cells
that select background bank 1 through the GB attribute bit 3.  The engine
loads the bank-0 overflow (tiles 256..263) at WSC tile 512 first, then the
cgb_tileset at 512, so bank-1 indices 0..3 hold the cgb tiles and 4..7 hold
the overflow tiles.  The test oracle deliberately does not import the engine
tile constants; it has its own copy of the layout.

Outputs c18_bg_data.c, c18_bg_data.h and c18_bg_data.json.  The generated
data is byte-for-byte deterministic and lives under wsc/build/.
"""

import argparse
import json
from pathlib import Path

WIDTH = 16
HEIGHT = 18
BANK0_TILES = 264            # 256 + 8 overflow tiles
CGB_TILES = 4
OVERFLOW_TILES = BANK0_TILES - 256


def tile_bytes(index, family):
    """Return one deterministic, unique 2bpp tile (16 bytes)."""
    data = []
    for row in range(8):
        lo = (index + row * 17 + family * 71) & 0xFF
        hi = ((index * 37) ^ (row * 29) ^ (family * 113)) & 0xFF
        if row == 0:
            lo = index & 0xFF
            hi = ((index >> 8) & 0x03) | (family << 6)
        data.extend((lo, hi))
    return data


def make_tiles(count, family):
    return [tile_bytes(i, family) for i in range(count)]


def make_palettes():
    palettes = []
    for p in range(7):
        colours = []
        for i in range(4):
            r = (p * 3 + i * 7 + 1) & 0x1F
            g = (p * 5 + i * 11 + 3) & 0x1F
            b = (p * 7 + i * 13 + 5) & 0x1F
            colours.append(r | (g << 5) | (b << 10))
        palettes.extend(colours)
    # UI palette 7: white, light grey, dark grey, black.
    for r, g, b in ((31, 31, 31), (20, 20, 20), (8, 8, 8), (0, 0, 0)):
        palettes.append(r | (g << 5) | (b << 10))
    return palettes


def make_map():
    tilemap = []
    attrs = []
    for cell in range(WIDTH * HEIGHT):
        tile = cell % 256
        attr = 0
        # The last 12 cells select bank-1 tiles 0..7.  Bank-1 0..3 are the
        # cgb_tileset (loaded second), 4..7 are the bank-0 overflow.
        if cell == WIDTH * HEIGHT - 12:
            tile, attr = 0, 0x08
        elif cell == WIDTH * HEIGHT - 11:
            tile, attr = 1, 0x08
        elif cell == WIDTH * HEIGHT - 10:
            tile, attr = 2, 0x08
        elif cell == WIDTH * HEIGHT - 9:
            tile, attr = 3, 0x08
        elif cell == WIDTH * HEIGHT - 8:
            tile, attr = 4, 0x08
        elif cell == WIDTH * HEIGHT - 7:
            tile, attr = 5, 0x08
        elif cell == WIDTH * HEIGHT - 6:
            tile, attr = 6, 0x08
        elif cell == WIDTH * HEIGHT - 5:
            tile, attr = 7, 0x08
        elif cell == WIDTH * HEIGHT - 4:
            tile, attr = 0x1C, 0
        elif cell == WIDTH * HEIGHT - 3:
            tile, attr = 0x1D, 0
        elif cell == WIDTH * HEIGHT - 2:
            tile, attr = 0x1E, 0
        elif cell == WIDTH * HEIGHT - 1:
            tile, attr = 0x1F, 0
        tilemap.append(tile)
        attrs.append(attr)
    return tilemap, attrs


def c_array(name, values, per_line=16):
    lines = ["const unsigned char __far {}[] = {{".format(name)]
    for start in range(0, len(values), per_line):
        chunk = values[start:start + per_line]
        lines.append("    " + ", ".join("0x{:02X}".format(v) for v in chunk) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True,
                        help="output directory (wsc/build/gamerom/c18)")
    args = parser.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    bank0 = make_tiles(BANK0_TILES, 0)
    cgb = make_tiles(CGB_TILES, 1)
    overflow = bank0[256:]
    palettes = make_palettes()
    tilemap, attrs = make_map()

    all_tiles = bank0 + cgb
    if len({bytes(t) for t in all_tiles}) != len(all_tiles):
        raise SystemExit("generated tiles are not unique")

    c_lines = [
        "/* Generated by wsc/tools/gen_c18_tiles.py. Do not edit. */",
        "#pragma bank 255",
        "",
        "#include <stdint.h>",
        '#include "gbs_types.h"',
        '#include "c18_bg_data.h"',
        "",
        "const struct tileset_t __far c18_bg_tileset = {",
        "    .n_tiles = {},".format(BANK0_TILES),
        "    .tiles = {",
    ]
    for tile in bank0:
        c_lines.append("        " + ", ".join("0x{:02X}".format(v) for v in tile) + ",")
    c_lines.extend(["    }", "};", ""])

    c_lines.extend([
        "const struct tileset_t __far c18_bg_cgb_tileset = {",
        "    .n_tiles = {},".format(CGB_TILES),
        "    .tiles = {",
    ])
    for tile in cgb:
        c_lines.append("        " + ", ".join("0x{:02X}".format(v) for v in tile) + ",")
    c_lines.extend(["    }", "};", ""])

    c_lines.append(c_array("c18_bg_tilemap", tilemap))
    c_lines.append("")
    c_lines.append(c_array("c18_bg_tilemap_attr", attrs))
    c_lines.append("")

    c_lines.append("const struct palette_t __far c18_bg_palette = {")
    c_lines.append("    .mask = 0xFF,")
    c_lines.append("    .palette = {")
    c_lines.append("        DMG_PALETTE(0, 1, 2, 3),")
    c_lines.append("        DMG_PALETTE(3, 2, 1, 0)")
    c_lines.append("    },")
    c_lines.append("    .cgb_palette = {")
    for p in range(8):
        words = palettes[p * 4:(p + 1) * 4]
        c_lines.append("        CGB_PALETTE(0x{:04X}, 0x{:04X}, 0x{:04X}, 0x{:04X}),".format(*words))
    c_lines.append("    }")
    c_lines.append("};")
    c_lines.append("")

    c_lines.append(c_array("c18_collisions", [0] * (WIDTH * HEIGHT)))
    c_lines.append("")
    c_lines.append("const struct background_t __far c18_bg = {")
    c_lines.append("    .width = {},".format(WIDTH))
    c_lines.append("    .height = {},".format(HEIGHT))
    c_lines.append("    .tileset = TO_FAR_PTR_T(c18_bg_tileset),")
    c_lines.append("    .cgb_tileset = TO_FAR_PTR_T(c18_bg_cgb_tileset),")
    c_lines.append("    .tilemap = TO_FAR_PTR_T(c18_bg_tilemap),")
    c_lines.append("    .cgb_tilemap_attr = TO_FAR_PTR_T(c18_bg_tilemap_attr)")
    c_lines.append("};")
    c_lines.append("")

    header = """/* Generated by wsc/tools/gen_c18_tiles.py. Do not edit. */
#ifndef C18_BG_DATA_H
#define C18_BG_DATA_H

#include "gbs_types.h"

extern const struct tileset_t __far c18_bg_tileset;
extern const struct tileset_t __far c18_bg_cgb_tileset;
extern const unsigned char __far c18_bg_tilemap[];
extern const unsigned char __far c18_bg_tilemap_attr[];
extern const struct palette_t __far c18_bg_palette;
extern const unsigned char __far c18_collisions[];
extern const struct background_t __far c18_bg;

#endif
"""
    data = {
        "width": WIDTH,
        "height": HEIGHT,
        "bank0_tiles": BANK0_TILES,
        "cgb_tiles": CGB_TILES,
        "overflow_tiles": OVERFLOW_TILES,
        "tileset": bank0,
        "cgb_tileset": cgb,
        "tilemap": tilemap,
        "attrs": attrs,
        "palette": palettes,
    }

    (out / "c18_bg_data.c").write_text("\n".join(c_lines), encoding="utf-8")
    (out / "c18_bg_data.h").write_text(header, encoding="utf-8")
    (out / "c18_bg_data.json").write_text(
        json.dumps(data, separators=(",", ":")) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
